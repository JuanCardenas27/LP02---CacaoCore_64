    def p_for_update_set_pluseq(self, p):
        """for_update : SET lvalue SWEET_PLUS expr"""
        instrs = []
        rhs_result = p[4].get('result') if isinstance(p[4], dict) else p[4]
        rhs_is_plain_imm = isinstance(rhs_result, (int, float)) and not p[4].get('code')
        rhs_is_struct_imm = (
            isinstance(rhs_result, dict)
            and rhs_result.get('kind') == self.OP_IMM
            and not p[4].get('code')
        )
        rhs_is_imm = rhs_is_plain_imm or rhs_is_struct_imm

        if rhs_is_imm:
            dest = self._force_reg(p[2])
            instrs.extend(dest['code'])
            imm_value = rhs_result.get('value') if isinstance(rhs_result, dict) else rhs_result
            instrs.append(f'ADD {dest["reg"]}, {imm_value}')
        else:
            src = self._force_reg(p[4])
            instrs.extend(src['code'])

            # Save RHS into a temporary memory slot to avoid clobbering
            temp_op = self._allocate_temp(8)
            # If the temp is a label (global), write/read using the label to
            # avoid depending on a register that dest generation may clobber.
            if temp_op.get('kind') == self.OP_ADDR_LABEL:
                temp_label = temp_op.get('label')
                instrs.append(f'MOVD [{temp_label}], {src["reg"]}')
                if src.get('owned'):
                    self._gestor.liberar(src['reg'])

                dest = self._force_reg(p[2])
                instrs.extend(dest['code'])

                loader = self._gestor.ocupar()
                instrs.append(f'MOVD {loader}, [{temp_label}]')
                instrs.append(f'ADD {dest["reg"]}, {loader}')
                self._gestor.liberar(loader)
            else:
                # If allocator returned a non-label temp (stack), synthesize
                # a small global label to hold the saved RHS across
                # materialization.
                label = f'temp_{self.label_count}'
                self.label_count += 1
                self.data.append(f'{label}_0 : 0')
                temp_label = f'{label}_0'
                instrs.append(f'MOVD [{temp_label}], {src["reg"]}')
                if src.get('owned'):
                    self._gestor.liberar(src['reg'])

                dest = self._force_reg(p[2])
                instrs.extend(dest['code'])

                loader = self._gestor.ocupar()
                instrs.append(f'MOVD {loader}, [{temp_label}]')
                instrs.append(f'ADD {dest["reg"]}, {loader}')
                self._gestor.liberar(loader)
            self._release_forced_reg(src, p[4])

        instrs.extend(self._emit_store(p[2]['result'], dest['reg']))

        if dest.get('owned'):
            self._gestor.liberar(dest['reg'])
        if p[2].get('owned'):
            self._gestor.liberar(p[2]['reg'])

        p[0] = {
            'code': instrs,
            'result': p[2]['result']
        }

