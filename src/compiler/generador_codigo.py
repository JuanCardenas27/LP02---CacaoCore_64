    def __init__(self):
        self._lex = AnalizadorLexico()
        self.errors: list[str] = []
        self._gestor = GestorRegistros()
        self.parser = yacc.yacc(
            module=self,
            debug=False,
            write_tables=False,
        )
        self.text = []
        self.data = []
        self.funcs = []
        self.label_count = 0
        self.scope_count = 0
        self.params_id = {} #func: {param:id} 
        self.function_stack = []
        self.float_counter = 0
        self.function_temp_size = 0
        self.used_string_labels = set()
        self.heap_cursor_label = '__heap_cursor'
        
    def parse(self, codigo: str, metadata) -> tuple[list[str], object]:
        """
        Analiza el código fuente y devuelve (errores, ast).

        Parámetros:
            codigo  -- cadena con el código CacaoScript preprocesado.

        Retorna:
            errores -- lista de strings con mensajes de error léxico+sintáctico.
            ast     -- NodoPrograma raíz del árbol, o None si no se pudo parsear.
        """
        # Cada compilación debe arrancar desde un estado limpio.
        self._gestor = GestorRegistros()
        self.text = []
        self.data = []
        self.funcs = []
        self.errors = []
        self.label_count = 0
        self.scope_count = 0
        self.params_id = {}
        self.function_stack = []
        self.float_counter = 0
        self.function_temp_size = 0
        self.used_string_labels = set()
        self.data = [f'{self.heap_cursor_label} : {HEAP_START}']
        _, _, _, self.num_table = self._lex.analize(codigo)
        dict_s = AnalizadorSemantico().parse(codigo, metadata)
        self.sim_table = dict_s['symbol_table']
        self.molds = dict_s['molds']
        self.type_sizes = dict_s['type_sizes']
        self.defined_symbols = dict_s['defined_symbols']
        self.functions = dict_s['functions']
        self.target = dict_s['target']
        self.string_pool = dict_s['string_pool']
        self.float_pool = dict_s['float_pool']
        # Reinicializar el lexer para el parser
        self._lex.lexer.input(codigo)
        self._lex.lexer.lineno = 1
        asmc = self.parser.parse(
            lexer=self._lex.lexer,
            tracking=True,
            debug=False
        )
        return self.errors, asmc
    
    def _symbol(self, name):
        current_func = self.function_stack[-1] if getattr(self, 'function_stack', []) else None
        
        if current_func:
            for sym in reversed(self.defined_symbols):
                if sym.get('name') == name and sym.get('scope') == current_func:
                    return sym
                    
        # Fallback to symbol table (for compatibility with globals, functions, etc.)
        return self.sim_table.get(name, {})
    
    def _is_global(self, symbol):
        return symbol['scope'] == 'global'

    def _type_size(self, type_name):
        if type_name in self.type_sizes:
            return self.type_sizes[type_name]

        mold = self.molds.get(type_name)
        if mold is not None:
            return mold.get('size', 0)

        return 8

    def _array_stride(self, operand):
        element_type = operand.get('type')
        element_size = operand.get('element_size') or self._type_size(element_type)
        if element_type in self.molds or element_type == 'text' or operand.get('is_ref'):
            element_size = self.target.get('pointer_size', 8) if getattr(self, 'target', None) else 8
        shape = list(operand.get('shape', []))

        if shape:
            tail = 1
            for dim in shape[1:]:
                if isinstance(dim, int) and dim > 0:
                    tail *= dim
            return element_size * tail

        return element_size

    def _mem_operand(self, name):
        sym = self._symbol(name)
        storage_class = sym.get('storage_class')
        kind = sym.get('kind')
        is_collection = kind in ('array', 'matrix')
        is_ref = (
            (sym.get('dims', 0) > 0)
            or is_collection
            or (sym.get('type') == 'text')
            or (sym.get('type') in self.molds)
        )

        # Preserve the original reference semantics for reference-like globals.
        # Global arrays, text values, and molds are stored as pointer-like
        # variables and must be loaded via `MOVD [label]` when accessing their
        # addressable contents.
        # Locals and parameters continue to use the same `is_ref` semantics.

        if storage_class == 'local':
            return {
                'kind': self.OP_STACK,
                'base': 'R13',
                'offset': f"__STACK_OFFSET_{sym['offset'] or 0}__",
                'type': sym.get('type'),
                'dims': sym.get('dims', 0),
                'shape': list(sym.get('shape', [])),
                'size': sym.get('size', 0),
                'text_size': sym.get('text_size', 0),
                'element_size': sym.get('element_size') or self._type_size(sym.get('type')),
                'is_ref': is_ref,
            }

        elif storage_class == 'param':
            func_sym = self.sim_table.get(sym.get('scope'), {}) if isinstance(sym, dict) else {}
            frame_size = func_sym.get('frame_size') or 0
            param_index = sym.get('parameter_index', 0)
            # Arguments are pushed right-to-left (reversed order in the caller).
            # push writes AT [R13] then decrements R13 by 8.
            # CALL also pushes the return address via push.
            # The callee prologue does SUB R13, frame_size.
            #
            # After prologue with frame_size=F:
            #   R13 = X - (num_args)*8 - 8 - F
            #   (X is original R13 before any pushes)
            #
            # First declared param (idx=0) is pushed LAST (reversed order),
            # so it sits at X - 8 = R13 + F + 16.
            # Each subsequent param (idx=k) sits 8 bytes higher: R13 + F + 16 + k*8.
            param_offset = frame_size + 16 + param_index * 8
            return {
                'kind': self.OP_STACK,
                'base': 'R13',
                'offset': f"__STACK_OFFSET_{param_offset}__",
                'type': sym.get('type'),
                'dims': sym.get('dims', 0),
                'shape': list(sym.get('shape', [])),
                'size': sym.get('size', 0),
                'text_size': sym.get('text_size', 0),
                'element_size': sym.get('element_size') or self._type_size(sym.get('type')),
                'is_ref': is_ref,
            }

        elif storage_class == 'field':
            current_mold = getattr(self, 'current_method_mold', None)
            mold = self.molds.get(current_mold, {}) if current_mold is not None else {}
            field_info = mold.get('fields', {}).get(name)
            if field_info is not None:
                return {
                    'kind': self.OP_FIELD,
                    'base': {
                        'kind': self.OP_REG,
                        'value': self.OHMY_REG,
                        'type': current_mold,
                        'is_ref': True,
                    },
                    'offset': field_info.get('offset', 0),
                    'type': field_info.get('type'),
                    'dims': field_info.get('dims', 0),
                    'shape': list(field_info.get('shape', [])),
                    'size': field_info.get('size', 0),
                    'text_size': field_info.get('text_size', 0),
                    'element_size': field_info.get('element_size') or self._type_size(field_info.get('type')),
                    'is_ref': (field_info.get('dims', 0) > 0) or (field_info.get('type') == 'text') or (field_info.get('type') in self.molds),
                }
            return {
                'kind': self.OP_GLOBAL,
                'label': name,
                'type': sym.get('type'),
                'dims': sym.get('dims', 0),
                'shape': list(sym.get('shape', [])),
                'size': sym.get('size', 0),
                'text_size': sym.get('text_size', 0),
                'element_size': sym.get('element_size') or self._type_size(sym.get('type')),
                'is_ref': is_ref,
            }

        else:
            return {
                'kind': self.OP_GLOBAL,
                'label': name,
                'type': sym.get('type'),
                'dims': sym.get('dims', 0),
                'shape': list(sym.get('shape', [])),
                'size': sym.get('size', 0),
                'text_size': sym.get('text_size', 0),
                'element_size': sym.get('element_size') or self._type_size(sym.get('type')),
                'is_ref': is_ref,
            }

    def _field_operand(self, base_operand, member_name):
        # Defensive: base_operand may sometimes be a plain name string (legacy paths).
        if isinstance(base_operand, str):
            base_operand = self._mem_operand(base_operand)

        base_type = base_operand.get('type')
        mold = self.molds.get(base_type, {})
        field = mold.get('fields', {}).get(member_name)

        if field is None:
            return None

        return {
            'kind': self.OP_FIELD,
            'base': base_operand,
            'offset': field.get('offset', 0),
            'type': field.get('type', 'unknown'),
            'dims': field.get('dims', 0),
            'shape': list(field.get('shape', [])),
            'size': field.get('size', 0),
            'text_size': field.get('text_size', 0),
            'element_size': field.get('element_size') or self._type_size(field.get('type')),
            'is_ref': (field.get('dims', 0) > 0) or (field.get('type') == 'text') or (field.get('type') in self.molds),
            'owner_kind': base_operand.get('kind'),
        }

    def _allocate_temp(self, size, heap=False):
        if not self.function_stack:
            # Global scope
            label = f'temp_{self.label_count}'
            self.label_count += 1
            for i in range((size + 7) // 8):
                self.data.append(f'{label}_{i} : 0')
            return {'kind': self.OP_ADDR_LABEL, 'label': f'{label}_0', 'is_ref': False}
        else:
            if heap:
                return {'kind': self.OP_HEAP, 'size': size, 'is_ref': False}
            # Local scope
            offset = self.function_temp_size
            self.function_temp_size += size
            # Returns a stack location representing the pointer/base address.
            # Because it's a temporary, we don't need a placeholder since it sits at the bottom of the stack frame.
            return {'kind': self.OP_STACK, 'base': 'R13', 'offset': offset, 'is_ref': False}

    def _address_of_operand(self, operand):
        code = []
        # Debug: log operand requests for address_of to help trace leaks
        try:
            with open('address_trace.log', 'a', encoding='utf-8') as fh:
                fh.write(f"_address_of_operand called with: {repr(operand)[:200]}\n")
        except Exception:
            pass

        if operand['kind'] == self.OP_GLOBAL:
            reg = self._gestor.ocupar()
            # If this global represents a reference-like variable (e.g.
            # a pointer stored in a global slot), load the pointer value.
            # Otherwise (plain data labels), return the label address so
            # callers can index into the data block.
            if operand.get('is_ref'):
                code.append(f'MOVD {reg}, [{operand["label"]}]')
            else:
                code.append(f'LEA {reg}, [{operand["label"]}]')
            try:
                with open('address_trace.log', 'a', encoding='utf-8') as fh:
                    fh.write(f"_address_of_operand returning: reg={reg} owned=True code={code}\n")
            except Exception:
                pass
            return code, reg, True

        if operand['kind'] == self.OP_STACK:
            reg = self._gestor.ocupar()
            code.append(f'MOVD {reg}, {operand["base"]}')
            off = operand.get('offset', 0)
            if off != 0 and off != '0':
                code.append(f'ADD {reg}, {off}')
            if operand.get('is_ref'):
                code.append(f'MOVD {reg}, [{reg}]')
            try:
                with open('address_trace.log', 'a', encoding='utf-8') as fh:
                    fh.write(f"_address_of_operand returning: reg={reg} owned=True code={code}\n")
            except Exception:
                pass
            return code, reg, True

        if operand['kind'] == self.OP_ADDR:
            try:
                with open('address_trace.log', 'a', encoding='utf-8') as fh:
                    fh.write(f"_address_of_operand returning: reg={operand['value']} owned=False code={code}\n")
            except Exception:
                pass
            return code, operand['value'], False

        if operand['kind'] == self.OP_FIELD:
            base_code, base_reg, base_owned = self._address_of_operand(operand['base'])
            code.extend(base_code)
            if operand['base'].get('needs_deref'):
                deref_reg = self._gestor.ocupar()
                code.append(f'MOVD {deref_reg}, [{base_reg}]')
                if base_owned:
                    self._gestor.liberar(base_reg)
                base_reg = deref_reg
                base_owned = True
            elif operand['base'].get('is_ref') and operand['base'].get('kind') == self.OP_FIELD:
                deref_reg = self._gestor.ocupar()
                code.append(f'MOVD {deref_reg}, [{base_reg}]')
                if base_owned:
                    self._gestor.liberar(base_reg)
                base_reg = deref_reg
                base_owned = True
            off = operand.get('offset', 0)
            if off != 0 and off != '0':
                # Avoid modifying a caller-owned base register (e.g., OHMY_REG).
                if not base_owned:
                    temp_reg = self._gestor.ocupar()
                    code.append(f'MOVD {temp_reg}, {base_reg}')
                    code.append(f'ADD {temp_reg}, {off}')
                    try:
                        with open('address_trace.log', 'a', encoding='utf-8') as fh:
                            fh.write(f"_address_of_operand returning: reg={temp_reg} owned=True code={code}\n")
                    except Exception:
                        pass
                    return code, temp_reg, True
                else:
                    code.append(f'ADD {base_reg}, {off}')
            try:
                with open('address_trace.log', 'a', encoding='utf-8') as fh:
                    fh.write(f"_address_of_operand returning: reg={base_reg} owned={base_owned} code={code}\n")
            except Exception:
                pass
            return code, base_reg, base_owned

        if operand['kind'] == self.OP_REG:
            # If the register is marked as a reference, it already contains the
            # base address of the object/slot. Do not perform an automatic
            # dereference here — callers expect the register to hold the
            # address itself. Return (code, reg, owned=False).
            if operand.get('is_ref'):
                return code, operand['value'], False
            # Non-reference registers: the register itself is the value.
            try:
                with open('address_trace.log', 'a', encoding='utf-8') as fh:
                    fh.write(f"_address_of_operand returning: reg={operand['value']} owned=False code={code}\n")
            except Exception:
                pass
            return code, operand['value'], False

        if operand['kind'] == self.OP_ADDR_LABEL:
            self.used_string_labels.add(operand['label'])
            reg = self._gestor.ocupar()
            code.append(f'LEA {reg}, [{operand["label"]}]')
            try:
                with open('address_trace.log', 'a', encoding='utf-8') as fh:
                    fh.write(f"_address_of_operand returning: reg={reg} owned=True code={code}\n")
            except Exception:
                pass
            return code, reg, True

        if operand['kind'] == self.OP_HEAP:
            base_reg = self._gestor.ocupar()
            end_reg = self._gestor.ocupar()
            aligned_size = ((int(operand.get('size', 0)) + 7) // 8) * 8
            code.extend([
                f'MOVD {base_reg}, [{self.heap_cursor_label}]',
                f'MOVD {end_reg}, {base_reg}',
                f'ADD {end_reg}, {aligned_size}',
                f'MOVD [{self.heap_cursor_label}], {end_reg}',
            ])
            self._gestor.liberar(end_reg)
            try:
                with open('address_trace.log', 'a', encoding='utf-8') as fh:
                    fh.write(f"_address_of_operand returning: reg={base_reg} owned=True code={code}\n")
            except Exception:
                pass
            return code, base_reg, True

        raise ValueError(f'Operando no soportado: {operand!r}')
        
    def _emit_load(self, reg, operand):

        code = []

        if operand['kind'] == self.OP_GLOBAL:
            code.append(
                f'MOVD {reg}, [{operand["label"]}]'
            )

        elif operand['kind'] == self.OP_STACK:
            addr = self._gestor.ocupar()
            code.append(f'MOVD {addr}, {operand["base"]}')
            off = operand.get('offset', 0)
            if off != 0 and off != '0':
                code.append(f'ADD {addr}, {off}')
            code.append(f'MOVD {reg}, [{addr}]')
            self._gestor.liberar(addr)

        elif operand['kind'] == self.OP_ADDR:
            code.append(f'MOVD {reg}, [{operand["value"]}]')

        elif operand['kind'] == self.OP_FIELD:
            addr_code, addr_reg, addr_owned = self._address_of_operand(operand)
            code.extend(addr_code)
            code.append(f'MOVD {reg}, [{addr_reg}]')
            if addr_owned:
                self._gestor.liberar(addr_reg)

        elif operand['kind'] == self.OP_REG:
            code.append(f'MOVD {reg}, {operand["value"]}')

        elif operand['kind'] == self.OP_IMM:
            code.append(f'MOVD {reg}, {operand["value"]}')

        elif operand['kind'] == self.OP_ADDR_LABEL:
            self.used_string_labels.add(operand['label'])
            code.append(f'LEA {reg}, [{operand["label"]}]')

        return code

    def _emit_store(self, operand, reg):
        code = []

        # (Instrumentation removed) 
        if operand['kind'] == self.OP_GLOBAL:
            store_reg = reg
            if store_reg == operand.get('label'):
                shadow = self._gestor.ocupar()
                code.append(f'MOVD {shadow}, {store_reg}')
                store_reg = shadow
            code.append(f'MOVD [{operand["label"]}], {store_reg}')

        elif operand['kind'] == self.OP_STACK:
            # Protect the source register from being clobbered by address
            # computation: copy `reg` into a shadow before computing address.
            store_reg = reg
            if isinstance(store_reg, str) and store_reg.startswith('R'):
                shadow = self._gestor.ocupar()
                code.append(f'MOVD {shadow}, {store_reg}')
                store_reg = shadow
            addr = self._gestor.ocupar()
            code.append(f'MOVD {addr}, {operand["base"]}')
            off = operand.get('offset', 0)
            if off != 0 and off != '0':
                code.append(f'ADD {addr}, {off}')
            code.append(f'MOVD [{addr}], {store_reg}')
            self._gestor.liberar(addr)
            if store_reg != reg:
                self._gestor.liberar(store_reg)

        elif operand['kind'] == self.OP_ADDR:
            # Protect the source register before writing to memory at the
            # address contained in `operand['value']`.
            store_reg = reg
            if isinstance(store_reg, str) and store_reg.startswith('R'):
                shadow = self._gestor.ocupar()
                code.append(f'MOVD {shadow}, {store_reg}')
                store_reg = shadow
            code.append(f'MOVD [{operand["value"]}], {store_reg}')
            if store_reg != reg:
                self._gestor.liberar(store_reg)

        elif operand['kind'] == self.OP_FIELD:
            # Protect the source register before computing the field address.
            store_reg = reg
            made_shadow = False
            if isinstance(store_reg, str) and store_reg.startswith('R'):
                shadow = self._gestor.ocupar()
                code.append(f'MOVD {shadow}, {store_reg}')
                store_reg = shadow
                made_shadow = True
            addr_code, addr_reg, addr_owned = self._address_of_operand(operand)
            code.extend(addr_code)
            if store_reg == addr_reg:
                # If address computation still returned the same reg, copy
                # the source again to a fresh shadow to avoid clobber.
                shadow2 = self._gestor.ocupar()
                code.append(f'MOVD {shadow2}, {reg}')
                store_reg = shadow2
                if made_shadow:
                    # release the first shadow because we replaced it
                    self._gestor.liberar(shadow)
            code.append(f'MOVD [{addr_reg}], {store_reg}')
            if addr_owned:
                self._gestor.liberar(addr_reg)
            if store_reg != reg:
                self._gestor.liberar(store_reg)

        elif operand['kind'] == self.OP_REG:
            code.append(f'MOVD [{operand["value"]}], {reg}')

        return code

    def _force_reg(self, expr):
        code = list(expr.get('code', [])) if isinstance(expr, dict) else []

        if not isinstance(expr, dict):
            reg = self._gestor.ocupar()
            code.append(f'MOVD {reg}, {expr}')
            return {'code': code, 'reg': reg, 'owned': True}

        result = expr.get('result')

        if expr.get('temp') and isinstance(result, str) and result.startswith('R'):
            return {'code': code, 'reg': result, 'owned': False}

        if isinstance(result, dict):
            if result.get('kind') == 'reg':
                return {'code': code, 'reg': result['value'], 'owned': False}
            reg = self._gestor.ocupar()
            code.extend(self._emit_load(reg, result))
            return {'code': code, 'reg': reg, 'owned': True}

        if isinstance(result, (int, float)):
            reg = self._gestor.ocupar()
            code.append(f'MOVD {reg}, {result}')
            return {'code': code, 'reg': reg, 'owned': True}

        if isinstance(result, str) and result.startswith('R'):
            return {'code': code, 'reg': result, 'owned': False}

        if isinstance(result, str):
            reg = self._gestor.ocupar()
            code.append(f'MOVD {reg}, {result}')
            return {'code': code, 'reg': reg, 'owned': True}

        reg = self._gestor.ocupar()
        code.append(f'MOVD {reg}, {result}')
        return {'code': code, 'reg': reg, 'owned': True}

    def _release_forced_reg(self, forced, expr=None):
        reg = forced.get('reg') if isinstance(forced, dict) else None
        if not reg:
            return
        if forced.get('owned'):
            self._gestor.liberar(reg)
            return
        if isinstance(expr, dict) and expr.get('temp') and reg in self._gestor.registros:
            self._gestor.liberar(reg)

    def _current_function_frame_size(self):
        if not self.function_stack:
            return 0
        func_name = self.function_stack[-1]
        sym = self._symbol(func_name)
        return sym.get('frame_size', 0) or 0

    def _current_function_exit_label(self):
        if not self.function_stack:
            return None
        return f'{self._function_asm_label(self.function_stack[-1])}_END'

    @staticmethod
    def _function_asm_label(function_name):
        safe = ''.join(ch if (ch.isalnum() or ch == '_') else '_' for ch in str(function_name))
        return f'FN_{safe}'

    @staticmethod
    def _format_text_cell(ch):
        """Renderiza una celda de texto como carácter de un byte cuando es posible."""
        if ch == '\n' or ch == "'":
            return ord(ch)
        return f"'{ch}'"

    @staticmethod
    def _text_value_string(value):
        if isinstance(value, dict):
            inner_value = value.get('value')
            if isinstance(inner_value, str):
                return inner_value
        if isinstance(value, str):
            return value
        return None

    def _text_value_size(self, value):
        text = self._text_value_string(value)
        if text is None:
            return 0
        return len(text) + 1

    def _expr_text_size(self, expr):
        if not isinstance(expr, dict):
            return 0
        size = int(expr.get('text_size') or 0)
        if size:
            return size
        value = expr.get('value')
        if isinstance(value, dict):
            size = int(value.get('size') or 0)
            if size:
                return size
            inner_value = value.get('value')
            if isinstance(inner_value, str):
                return len(inner_value) + 1
        if expr.get('type') == 'text':
            return self._text_value_size(value)
        return 0

    @staticmethod
    def _normalize_data_label(label_hint):
        raw = str(label_hint or '').lower()
        out = []
        for ch in raw:
            if ('a' <= ch <= 'z') or ('0' <= ch <= '9') or ch == '_':
                out.append(ch)
            else:
                out.append('_')
        normalized = ''.join(out).strip('_')
        if not normalized:
            return 'text'
        if not (('a' <= normalized[0] <= 'z') or normalized[0] == '_'):
            normalized = f'_{normalized}'
        return normalized

    def _materialize_text_storage(self, name_hint, value, owner_sym=None, owner_is_global=None):
        text = self._text_value_string(value)
        if text is None:
            return None

        if owner_is_global is None and owner_sym is not None:
            owner_is_global = self._is_global(owner_sym)

        if owner_is_global:
            safe_hint = self._normalize_data_label(name_hint)
            base_label = f'{safe_hint}_text_{self.label_count}'
            self.label_count += 1
            for i, ch in enumerate(text):
                self.data.append(f'{base_label}_{i} : {self._format_text_cell(ch)}')
            self.data.append(f'{base_label}_{len(text)} : 0')
            return {
                'code': [],
                'result': {
                    'kind': self.OP_ADDR_LABEL,
                    'label': f'{base_label}_0',
                },
                'type': 'text',
                'text_size': len(text) + 1,
            }

        temp_operand = self._allocate_temp(len(text) + 1, heap=True)
        addr_code, addr_reg, addr_owned = self._address_of_operand(temp_operand)
        init_code = list(addr_code)
        cursor_reg = self._gestor.ocupar()
        init_code.append(f'MOVD {cursor_reg}, {addr_reg}')
        for ch in text:
            init_code.append(f'MOVD [{cursor_reg}], {self._format_text_cell(ch)}')
            init_code.append(f'ADD {cursor_reg}, 8')
        init_code.append(f'MOVD [{cursor_reg}], 0')
        self._gestor.liberar(cursor_reg)
        return {
            'code': init_code,
            'result': {
                'kind': self.OP_REG,
                'value': addr_reg,
                'is_ref': True,
            },
            'type': 'text',
            'temp': True,
            'reg': addr_reg,
            'owned': addr_owned,
            'text_size': len(text) + 1,
        }
    
    
