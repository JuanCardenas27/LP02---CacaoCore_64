    # ── Declaración let ───────────────────────────────────────────────────

    def p_let_stmt(self, p):
        """
        let_stmt : LET ID COLON type_annot opt_dims opt_initializer
        """
        name = p[2]
        tipo = p[4]
        dims_info = p[5] or {'dims': 0, 'shape': []}
        initializer = p[6]

        defecto = 0
        if tipo == "int":
            defecto = 0
        elif tipo == "float":
            defecto = 0.0
        elif tipo == "text":
            defecto = "' '"
        elif tipo == "bool":
            defecto = 0

        owner_sym = self._symbol(name)

        # helper to extract integer from dimension spec
        def _to_int_dim(x):
            # Accept several possible node shapes: dict (generated by parser),
            # numeric literal, or a syntax node referencing a symbol name.
            if isinstance(x, dict):
                r = x.get('result')
                if isinstance(r, str):
                    return int(self.sim_table.get(r, {}).get('value', 0))
                if isinstance(r, dict):
                    return int(r.get('value', r.get('result', 0)))
                return int(r or 0)
            # Numeric literals
            if isinstance(x, (int, float)):
                return int(x)
            # String symbol name
            if isinstance(x, str):
                return int(self.sim_table.get(x, {}).get('value', 0))
            # Syntax node (NodoTerminal/NodoID): try to extract a name/value
            name = getattr(x, 'valor', None) or getattr(x, 'nombre', None)
            if isinstance(name, str):
                return int(self.sim_table.get(name, {}).get('value', 0))
            return 0

        def _scalar_repr(value):
            if isinstance(value, dict):
                if 'value' in value:
                    return value['value']
                if value.get('kind') == 'global' and value.get('label') in self.float_pool:
                    return self.float_pool[value['label']]
                if 'label' in value:
                    label = value['label']
                    if label in self.float_pool:
                        return self.float_pool[label]
                    return label
                if 'result' in value:
                    return _scalar_repr(value['result'])
            if isinstance(value, str) and value in self.float_pool:
                return self.float_pool[value]
            return value

        dims = dims_info.get('dims', 0)
        shape = dims_info.get('shape', [])
        is_ref_decl = dims > 0 or tipo == 'text' or tipo in self.molds

        def _array_slot_size(element_type):
            if element_type == 'text' or element_type in self.molds:
                return self.target.get('pointer_size', 8) if getattr(self, 'target', None) else 8
            return self._type_size(element_type)

        # Reference-like declarations (molds/arrays/text) are stored as pointers.
        if is_ref_decl:
            target_operand = self._mem_operand(name)
            if self._is_global(owner_sym):
                self.data.append(f'{name} : 0')

            init_code = []

            if isinstance(initializer, list):
                # Array literal initializer [1, 2, 3]
                size = 0
                lengths = [_to_int_dim(x) for x in shape]
                total = 1
                for v in lengths:
                    total *= v
                base_size = self._type_size(tipo)
                size = total * base_size
                if size <= 0:
                    size = max(len(initializer), 1) * base_size
                # If this is a global declaration with a static initializer,
                # emit the element values directly into the .data section
                # and point the variable to that static area. This avoids
                # generating runtime stores and ensures initializer slots
                # exist for examples like matmul.
                if self._is_global(owner_sym):
                    base_label = f'{name}_data'
                    # Emit contiguous data labels for each element
                    # Determine how many data slots to emit. If the declared
                    # total size is known (>0) use it, otherwise fall back to
                    # the number of initializer elements. Pad with default
                    # values when initializer has fewer elements than total.
                    elem_count = total if total > 0 else len(initializer)
                    inserts = []
                    runtime_inits = []
                    for i in range(elem_count):
                        label = f'{base_label}_{i}'
                        if i < len(initializer):
                            val = initializer[i]
                            scalar = _scalar_repr(val)
                        else:
                            scalar = defecto

                        # If scalar is a register name or non-serializable,
                        # emit an empty slot in .data and schedule a runtime
                        # initialization that stores the computed value into
                        # the label address. This handles summons and other
                        # dynamic initializers.
                        if scalar is None or (isinstance(scalar, str) and scalar.startswith('R')):
                            decl = f'{label} : 0'
                            if decl not in self.data and decl not in inserts:
                                inserts.append(decl)

                            # Generate runtime init code to store the value
                            # Evaluate the initializer expression into a register
                            val_force = self._force_reg(val)
                            # Allocate an address register and store
                            addr_reg = self._gestor.ocupar()
                            runtime_inits.extend(val_force['code'])
                            store_reg = val_force['reg']
                            if store_reg == addr_reg:
                                shadow = self._gestor.ocupar()
                                runtime_inits.append(f'MOVD {shadow}, {store_reg}')
                                store_reg = shadow
                            runtime_inits.append(f'LEA {addr_reg}, [{label}]')
                            runtime_inits.append(f'MOVD [{addr_reg}], {store_reg}')
                            if val_force.get('owned'):
                                self._gestor.liberar(val_force['reg'])
                            self._gestor.liberar(addr_reg)
                        else:
                            decl = f'{label} : {scalar}'
                            if decl not in self.data and decl not in inserts:
                                inserts.append(decl)

                    if inserts:
                        # Place the element declarations before existing .data
                        # entries, preserving ascending index order.
                        self.data = inserts + self.data

                    # Make the variable point to the first element and
                    # prepend any runtime initializers so they run at startup.
                    ptr_reg = self._gestor.ocupar()
                    init_code.extend(runtime_inits)
                    init_code.append(f'LEA {ptr_reg}, [{base_label}_0]')
                    init_code.extend(self._emit_store(target_operand, ptr_reg))
                    self._gestor.liberar(ptr_reg)
                else:
                    temp_operand = self._allocate_temp(size, heap=True)
                    addr_code, addr_reg, addr_owned = self._address_of_operand(temp_operand)
                    init_code.extend(addr_code)

                    slot_size = _array_slot_size(tipo)

                    for i, val in enumerate(initializer):
                        if i >= total:
                            break
                        val_force = self._force_reg(val)
                        init_code.extend(val_force['code'])

                        elem_addr_reg = self._gestor.ocupar()
                        store_reg = val_force['reg']
                        if store_reg == elem_addr_reg:
                            shadow = self._gestor.ocupar()
                            init_code.append(f'MOVD {shadow}, {store_reg}')
                            store_reg = shadow
                        base_reg = self._gestor.ocupar()
                        init_code.append(f'MOVD {base_reg}, {addr_reg}')
                        init_code.append(f'MOVD {elem_addr_reg}, {addr_reg}')
                        if i > 0:
                            init_code.append(f'ADD {elem_addr_reg}, {i * slot_size}')
                        init_code.append(f'MOVD [{elem_addr_reg}], {store_reg}')
                        self._gestor.liberar(elem_addr_reg)
                        if val_force.get('owned'):
                            self._gestor.liberar(val_force['reg'])

                    init_code.extend(self._emit_store(target_operand, addr_reg))
                    if addr_owned:
                        self._gestor.liberar(addr_reg)

            elif initializer is not None:
                # Scalar initializer: text values are materialized into their own backing storage.
                if tipo == 'text':
                    materialized = self._materialize_text_storage(name, initializer.get('value') if isinstance(initializer, dict) else initializer, owner_sym)
                    if materialized is not None:
                        init_code.extend(materialized['code'])
                        if materialized['result']['kind'] == self.OP_REG:
                            init_code.extend(self._emit_store(target_operand, materialized['result']['value']))
                            if materialized.get('owned'):
                                self._gestor.liberar(materialized['result']['value'])
                        else:
                            src_force = self._force_reg(materialized)
                            init_code.extend(src_force['code'])
                            init_code.extend(self._emit_store(target_operand, src_force['reg']))
                            if src_force.get('owned'):
                                self._gestor.liberar(src_force['reg'])
                    else:
                        src_force = self._force_reg(initializer)
                        init_code.extend(src_force['code'])
                        init_code.extend(self._emit_store(target_operand, src_force['reg']))
                        if src_force.get('owned'):
                            self._gestor.liberar(src_force['reg'])
                else:
                    src_force = self._force_reg(initializer)
                    init_code.extend(src_force['code'])
                    init_code.extend(self._emit_store(target_operand, src_force['reg']))
                    if src_force.get('owned'):
                        self._gestor.liberar(src_force['reg'])
            else:
                # No initializer: we must allocate space and point to it
                if tipo == 'text':
                    ptr_reg = self._gestor.ocupar()
                    init_code.append(f'MOVD {ptr_reg}, 0')
                    init_code.extend(self._emit_store(target_operand, ptr_reg))
                    self._gestor.liberar(ptr_reg)
                else:
                    # Array or Mold
                    size = 0
                    if dims > 0:
                        lengths = [_to_int_dim(x) for x in shape]
                        total = 1
                        for v in lengths:
                            total *= v
                        base_size = _array_slot_size(tipo)
                        size = total * base_size
                    elif tipo in self.molds:
                        size = self.molds[tipo].get('size', 0)
                    
                    # If we couldn't compute a positive size (e.g. dims refer
                    # to previously-declared symbols) try resolving shape
                    # entries via the symbol table as a fallback. If that
                    # still fails, conservatively assume 1 for each unknown
                    # dimension so we still allocate space for globals.
                    if size == 0 and dims > 0:
                        base_size = _array_slot_size(tipo)
                        lengths = []
                        for x in shape:
                            l = _to_int_dim(x)
                            if l == 0:
                                # Try alternative resolutions from symbol table
                                if isinstance(x, str):
                                    l = int(self.sim_table.get(x, {}).get('value', 0) or 0)
                                elif isinstance(x, dict):
                                    r = x.get('result')
                                    if isinstance(r, str):
                                        l = int(self.sim_table.get(r, {}).get('value', 0) or 0)
                                    elif isinstance(r, dict):
                                        l = int(r.get('value', r.get('result', 0)) or 0)
                                else:
                                    name_attr = getattr(x, 'valor', None) or getattr(x, 'nombre', None)
                                    if isinstance(name_attr, str):
                                        l = int(self.sim_table.get(name_attr, {}).get('value', 0) or 0)
                            if l == 0:
                                # Unable to resolve at compile-time — conservatively
                                # assume 1 so codegen can continue.
                                l = 1
                            lengths.append(l)
                        total = 1
                        for v in lengths:
                            total *= v
                        size = total * base_size

                    # If semantic information already contains a computed
                    # size for this symbol, prefer it (this happens when
                    # dimensions reference previously-declared symbols).
                    if size == 0 and owner_sym is not None:
                        syminfo = self._symbol(name)
                        sem_size = syminfo.get('size', 0) if isinstance(syminfo, dict) else 0
                        if sem_size:
                            size = sem_size

                    if size > 0:
                        base_size = _array_slot_size(tipo)
                        # For global arrays, prefer emitting a static .data
                        # area so the assembler/linker see concrete labels
                        # (avoids runtime temp allocation). If semantic
                        # information provides a size, emit that many
                        # element labels and point the variable to the
                        # first element.
                        if self._is_global(owner_sym):
                            # Prefer semantic table size when available
                            sem = self._symbol(name) or {}
                            sem_size = sem.get('size', 0) if isinstance(sem, dict) else 0
                            if sem_size:
                                elem_count = sem_size // base_size if base_size else 0
                            else:
                                elem_count = size // base_size if base_size else 0
                            base_label = f'{name}_data'
                            inserts = []
                            for i in range(elem_count):
                                decl = f'{base_label}_{i} : 0'
                                if decl not in self.data and decl not in inserts:
                                    inserts.append(decl)
                            if inserts:
                                self.data = inserts + self.data
                            ptr_reg = self._gestor.ocupar()
                            init_code.append(f'LEA {ptr_reg}, [{base_label}_0]')
                            init_code.extend(self._emit_store(target_operand, ptr_reg))
                            self._gestor.liberar(ptr_reg)
                        else:
                            temp_operand = self._allocate_temp(size, heap=True)
                            addr_code, addr_reg, addr_owned = self._address_of_operand(temp_operand)
                            init_code.extend(addr_code)
                            init_code.extend(self._emit_store(target_operand, addr_reg))
                            if addr_owned:
                                self._gestor.liberar(addr_reg)

            p[0] = {
                'code': init_code,
                'result': name,
                'sect': '.data'
            }
            return

        # Scalar without initializer
        if dims == 0 and initializer is None:
            if self._is_global(owner_sym):
                self.data.append(f'{name} : {defecto}')
            p[0] = {
                'code': [],
                'result': name,
                'sect': '.data'
            }
            return

        # Scalar with initializer
        if dims == 0 and initializer is not None:
            # reuse existing handler logic
            value = initializer
            if isinstance(value, dict):
                init_value = value.get('result')
                code = list(value.get('code', []))
            else:
                init_value = value
                code = []

            target_operand = self._mem_operand(name)

            if isinstance(value, dict) and value.get('temp'):
                if self._is_global(owner_sym):
                    self.data.append(f'{name} : 0')
                code.extend(self._emit_store(target_operand, init_value))
                if isinstance(init_value, str) and init_value.startswith('R'):
                    self._gestor.liberar(init_value)

            elif isinstance(init_value, dict) and init_value.get('kind') == 'global':
                if self._is_global(owner_sym):
                    self.data.append(f"{name} : 0")
                r1 = self._gestor.ocupar()
                code.extend([
                    f'MOVD {r1}, [{init_value["label"]}]',
                ])
                code.extend(self._emit_store(target_operand, r1))
                self._gestor.liberar(r1)

            else:
                if self._is_global(owner_sym):
                    self.data.append(f'{name} : 0')
                forced = self._force_reg(value)
                code.extend(forced['code'])
                code.extend(self._emit_store(target_operand, forced['reg']))
                if forced.get('owned'):
                    self._gestor.liberar(forced['reg'])

            p[0] = {
                'code': code,
                'result': name,
                'sect': '.data'
            }
            return



