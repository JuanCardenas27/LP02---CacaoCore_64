    def p_set_assign(self, p):
        """set_stmt : SET lvalue ASSIGN expr"""
        instrs = []
        instrs.extend(p[2]['code'])

        if p[2].get('type') == 'text':
            dest_symbol = p[2].get('symbol') or self._symbol(
                p[2]['result'].get('label', '')
            )
            owner_is_global = None
            if p[2]['result'].get('kind') == self.OP_FIELD:
                owner_is_global = p[2]['result'].get('owner_kind') == self.OP_GLOBAL
            materialized = self._materialize_text_storage(
                dest_symbol.get('name', p[2]['result'].get('label', 'text')),
                p[4].get('value') if isinstance(p[4], dict) else p[4],
                dest_symbol,
                owner_is_global=owner_is_global
            )
            if materialized is not None:
                if materialized['result']['kind'] == self.OP_REG:
                    src = {
                        'code': materialized['code'],
                        'reg': materialized['result']['value'],
                        'owned': materialized.get('owned', False),
                    }
                else:
                    src = self._force_reg(materialized)
            else:
                src = self._force_reg(p[4])
        else:
            src = self._force_reg(p[4])

        instrs.extend(src['code'])
        instrs.extend(self._emit_store(p[2]['result'], src['reg']))

        self._release_forced_reg(src, p[4])
        if p[2].get('owned'):
            self._gestor.liberar(p[2]['reg'])

        p[0] = {
            'code': instrs,
            'result': p[2]['result']
        }


    def p_set_pluseq(self, p):
        """set_stmt : SET lvalue SWEET_PLUS expr"""
        src = self._force_reg(p[4])

        instrs = []
        instrs.extend(src['code'])

        # If RHS has non-trivial code, store it into a temporary memory
        # slot to avoid being clobbered while materializing the lvalue.
        # Initialize preservation helpers to avoid referencing undefined
        # variables later in the function when RHS has no code path.
        saved_label = None
        saved_addr_reg = None
        saved_addr_owned = False
        src_reg = None
        src_owned = False
        # Always preserve RHS into a label-backed temporary to avoid any
        # register-reuse or materialization clobbering during LHS generation.
        label = f'pluseq_temp_{self.label_count}'
        self.label_count += 1
        self.data.append(f'{label}_0 : 0')
        temp_label = f'{label}_0'
        instrs.append(f'MOVD [{temp_label}], {src["reg"]}')
        if src.get('owned'):
            self._gestor.liberar(src['reg'])
        saved_addr_reg = None
        saved_addr_owned = False
        saved_label = temp_label
        src_reg = None
        src_owned = False
        

        dest = self._force_reg(p[2])
        instrs.extend(dest['code'])

        # If we stored RHS to memory, load it back into a register now.
        if saved_label is not None:
            loader = self._gestor.ocupar()
            instrs.append(f'MOVD {loader}, [{saved_label}]')
            instrs.append(f'ADD {dest["reg"]}, {loader}')
            self._gestor.liberar(loader)
        elif saved_addr_reg is not None:
            loader = self._gestor.ocupar()
            instrs.append(f'MOVD {loader}, [{saved_addr_reg}]')
            instrs.append(f'ADD {dest["reg"]}, {loader}')
            self._gestor.liberar(loader)
            if saved_addr_owned:
                self._gestor.liberar(saved_addr_reg)
        else:
            instrs.append(f'ADD {dest["reg"]}, {src_reg}')

        instrs.extend(self._emit_store(p[2]['result'], dest['reg']))

        if src_reg and src_owned and src_reg in self._gestor.registros:
            self._gestor.liberar(src_reg)
        self._release_forced_reg(src, p[4])
        if dest.get('owned'):
            self._gestor.liberar(dest['reg'])
        if p[2].get('owned'):
            self._gestor.liberar(p[2]['reg'])

        p[0] = {
            'code': instrs,
            'result': p[2]['result']
        }

