    def _handle_by_type(self, name, tipo, arg, owner_sym=None):
        n_code = []
        owner_sym = owner_sym or {}
        init_value = arg.get('result')
        target_operand = self._mem_operand(name)

        def _scalar_repr(value):
            if isinstance(value, dict):
                if 'value' in value:
                    return value['value']
                if value.get('kind') == 'global' and value.get('label') in self.float_pool:
                    return self.float_pool[value['label']]
                if 'label' in value:
                    label = value['label']
                    if label in self.float_pool:
                        return self.float_pool[label]
                    return label
                if 'result' in value:
                    return _scalar_repr(value['result'])
            if isinstance(value, str) and value in self.float_pool:
                return self.float_pool[value]
            return value

        if tipo == 'text':
            self.sim_table.setdefault(name, {})['type'] = tipo

            if self._is_global(owner_sym):
                self.data.append(f"{name} : 0")

            materialized = self._materialize_text_storage(
                name,
                arg.get('value') if isinstance(arg, dict) else arg,
                owner_sym
            )
            if materialized is not None:
                n_code.extend(materialized['code'])
                init_value = materialized['result']
            else:
                forced = self._force_reg(arg)
                n_code.extend(forced['code'])
                n_code.extend(self._emit_store(target_operand, forced['reg']))
                if forced.get('owned'):
                    self._gestor.liberar(forced['reg'])

        elif arg.get('temp'):
            if self._is_global(owner_sym):
                self.data.append(f'{name} : 0')
            n_code.extend(self._emit_store(target_operand, init_value))

        elif isinstance(init_value, dict) and init_value.get('kind') == 'global':
            if self._is_global(owner_sym):
                self.data.append(f"{name} : 0")
            r1 = self._gestor.ocupar()
            n_code.extend([
                f'MOVD {r1}, [{init_value["label"]}]',
            ])
            n_code.extend(self._emit_store(target_operand, r1))
            self._gestor.liberar(r1)

        else:
            if self._is_global(owner_sym):
                self.data.append(f'{name} : 0')
            forced = self._force_reg(arg)
            n_code.extend(forced['code'])
            n_code.extend(self._emit_store(target_operand, forced['reg']))
            if forced.get('owned'):
                self._gestor.liberar(forced['reg'])

        return n_code

            

